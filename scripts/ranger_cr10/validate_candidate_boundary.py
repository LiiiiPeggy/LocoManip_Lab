args = ap.parse_args()


def sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


# ---------------------------------------------------------------------------------------------
# MuJoCo forward kinematics
# ---------------------------------------------------------------------------------------------
MODEL = mujoco.MjModel.from_xml_path(str(SCENE))
DATA = mujoco.MjData(MODEL)
HOME = MODEL.key("home").id
BID = {mujoco.mj_id2name(MODEL, mujoco.mjtObj.mjOBJ_BODY, i): i for i in range(MODEL.nbody)}
ARM_ADR = [
    MODEL.jnt_qposadr[mujoco.mj_name2id(MODEL, mujoco.mjtObj.mjOBJ_JOINT, f"cr10_joint{i}")] for i in range(1, 7)
]
JOINT_IDS = [mujoco.mj_name2id(MODEL, mujoco.mjtObj.mjOBJ_JOINT, f"cr10_joint{i}") for i in range(1, 7)]
LO = np.array([MODEL.jnt_range[j][0] for j in JOINT_IDS])
HI = np.array([MODEL.jnt_range[j][1] for j in JOINT_IDS])


def fk(q: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Full forward kinematics for the six arm joints; returns Link5 -> Link3 relative pose."""
    mujoco.mj_resetDataKeyframe(MODEL, DATA, HOME)
    for address, value in zip(ARM_ADR, q):
        DATA.qpos[address] = float(value)
    mujoco.mj_kinematics(MODEL, DATA)
    r3 = np.array(DATA.xmat[BID["cr10_Link3"]], dtype=np.float64).reshape(3, 3)
    p3 = np.array(DATA.xpos[BID["cr10_Link3"]], dtype=np.float64)
    r5 = np.array(DATA.xmat[BID["cr10_Link5"]], dtype=np.float64).reshape(3, 3)
    p5 = np.array(DATA.xpos[BID["cr10_Link5"]], dtype=np.float64)
    return r3.T @ r5, r3.T @ (p5 - p3), r3, p3, r5, p5


# ---------------------------------------------------------------------------------------------
# Candidate scan (main process): used only to choose where along a path to evaluate
# ---------------------------------------------------------------------------------------------
def is_contact(result: dict) -> bool:
    return result["status"] == "intersecting" or (
        result["status"] == "separated" and np.isfinite(result["distance"]) and result["distance"] <= CONTACT_TOL
    )


def bisect_candidate(builder, s_lo: float, s_hi: float, pieces3, pieces5, iterations: int = 16) -> tuple[float, float]:
    """Tighten the candidate's own zero crossing; the reference decides the final label."""
    for _ in range(iterations):
        mid = 0.5 * (s_lo + s_hi)
        rotation, translation, _ = builder(mid)
        if is_contact(union_query(pieces3, pieces5, rotation, translation)):
            s_hi = mid
        else:
            s_lo = mid
    return s_lo, s_hi


def scan_and_boundary(builder, pieces3, pieces5, s_max: float = 1.6, points: int = 41) -> dict:
    grid = np.linspace(0.0, s_max, points)
    scan = []
    for s in grid:
        rotation, translation, _ = builder(float(s))
        scan.append((float(s), union_query(pieces3, pieces5, rotation, translation)))
    first = None
    for index, (_, result) in enumerate(scan):
        if is_contact(result):
            first = index
            break
    boundary = None
    if first is not None:
        if first == 0:
            boundary = (0.0, 0.0)
        else:
            boundary = bisect_candidate(builder, scan[first - 1][0], scan[first][0], pieces3, pieces5)
    finite = [(s, r["distance"]) for s, r in scan if r["status"] == "separated" and np.isfinite(r["distance"])]
    closest = min(finite, key=lambda item: item[1]) if finite else (None, None)
    return dict(scan=scan, boundary=boundary, closest=closest, first_contact_index=first)


def s_list_from_boundary(boundary: tuple[float, float] | None, closest_s: float | None) -> list[float]:
    if boundary is not None and boundary[1] > 0:
        s_b = float(boundary[1])
        fractions = [0.15, 0.30, 0.45, 0.60, 0.72, 0.82, 0.90, 0.96]
        values = [0.0] + [s_b * f for f in fractions] + [s_b * f for f in (1.0, 1.02, 1.05, 1.10, 1.20, 1.35)]
    elif boundary is not None:  # already in contact at the seed
        values = [0.0] + [0.5, 1.0, 1.5, 2.0]
    else:
        anchor = float(closest_s) if closest_s is not None else 0.75
        values = list(np.linspace(0.0, 1.5, 13))
        values += [anchor]
    return sorted({round(float(v), 7) for v in values if v >= 0.0})


# ---------------------------------------------------------------------------------------------
# Sample construction
# ---------------------------------------------------------------------------------------------
def payload(sample_id: str, kind: str, cluster: str, seed: str, s: float, rotation: np.ndarray,
            translation: np.ndarray, **extra) -> dict:
    row = dict(
        id=sample_id,
        type=kind,
        cluster=cluster,
        seed=seed,
        s=float(s),
        rotation=np.asarray(rotation, dtype=np.float64).tolist(),
        translation=np.asarray(translation, dtype=np.float64).tolist(),
    )
    row.update(extra)
    return row


def main() -> None:
    out_dir = ROOT / args.out
    out_dir.mkdir(parents=True, exist_ok=True)

    mesh3 = trimesh.load(str(MESH_DIR / "Link3.STL"), force="mesh", process=False)
    mesh5 = trimesh.load(str(MESH_DIR / "Link5.STL"), force="mesh", process=False)
    hull3_pts = np.asarray(mesh3.convex_hull.vertices)
    hull5_pts = np.asarray(mesh5.convex_hull.vertices)
    centroid5 = np.asarray(mesh5.vertices, dtype=np.float64).mean(axis=0)
    pieces_dir = ROOT / args.pieces
    pieces3 = load_pieces("cr10_Link3", pieces_dir)
    pieces5 = load_pieces("cr10_Link5", pieces_dir)
    if not pieces3 or not pieces5:
        raise SystemExit(f"no pieces under {pieces_dir}")

    inventory = dict(
        candidate_pieces=dict(
            Link3=len(pieces3),
            Link5=len(pieces5),
            files={name: sha256(pieces_dir / f"{name}.npz") for name, _ in pieces3 + pieces5},
        ),
        source_meshes={
            "Link3.STL": sha256(MESH_DIR / "Link3.STL"),
            "Link5.STL": sha256(MESH_DIR / "Link5.STL"),
        },
        scripts={
            "candidate_eval.py": sha256(HERE / "candidate_eval.py"),
            "validate_candidate_boundary.py": sha256(HERE / "validate_candidate_boundary.py"),
            "reference_geometry.py": sha256(HERE / "reference_geometry.py"),
            "triangle_distance.py": sha256(HERE / "triangle_distance.py"),
            "convex_distance.py": sha256(HERE / "convex_distance.py"),
        },
        contact_tolerance_m=CONTACT_TOL,
        bins_m=dict(zip(BIN_LABELS, BINS)),
        reference="original Link3/Link5 STL triangle meshes (not the MuJoCo collision hulls)",
    )

    poses = np.load(POSES)["poses"]
    rng = np.random.default_rng(args.seed)

    # --- A: regression poses ------------------------------------------------------------------
    a_payloads = []
    for index in range(93, 99):
        q = poses[index]
        rotation, translation, *_ = fk(q)
        a_payloads.append(
            payload(f"A{index}", "A", "A", f"pose{index}", 0.0, rotation, translation, q=q.tolist())
        )

    # --- C seed screening: multi-start joint sampling -----------------------------------------
    started = time.time()
    q_all = rng.uniform(LO, HI, size=(args.joint_samples, 6))
    excluded = 0
    if args.exclude_q:
        dev_q = np.load(args.exclude_q)
        if dev_q.ndim != 2 or dev_q.shape[1] != 6:
            raise SystemExit(f"{args.exclude_q}: expected shape (N, 6), got {dev_q.shape}")
        keep = np.array([
            float(np.min(np.max(np.abs(dev_q - q), axis=1))) >= args.exclude_tol for q in q_all
        ])
        excluded = int((~keep).sum())
        q_all = q_all[keep]
        print(f"excluded {excluded} joint samples within L-infinity {args.exclude_tol} of a development seed; "
              f"{len(q_all)} remain")
    rel_r, rel_t, hull_d = [], [], []
    for q in q_all:
        rotation, translation, *_ = fk(q)
        result = union_query(
            [("hull3", hull3_pts)], [("hull5", hull5_pts)], rotation, translation, tol=1e-6
        )
        distance = 0.0 if result["status"] == "intersecting" else result["distance"]
        rel_r.append(rotation)
        rel_t.append(translation)
        hull_d.append(distance)
    hull_d = np.asarray(hull_d)
    print(f"joint sampling: {args.joint_samples} configs in {time.time() - started:.1f}s; "
          f"hull contact {int((hull_d == 0).sum())}, hull < 20 mm {int((hull_d < 0.02).sum())}, "
          f"hull < 30 mm {int((hull_d < 0.03).sum())}")

    features = np.concatenate(
        [np.asarray(rel_t), np.asarray([Rotation.from_matrix(r).as_rotvec() for r in rel_r])], axis=1
    )
    features = (features - features.mean(axis=0)) / np.maximum(features.std(axis=0), 1e-9)

    def farthest_point(data: np.ndarray, count: int) -> list[int]:
        selected = [int(np.argmin(hull_d))]
        distance = np.linalg.norm(data - data[selected[0]], axis=1)
        for _ in range(1, count):
            index = int(np.argmax(distance))
            selected.append(index)
            distance = np.minimum(distance, np.linalg.norm(data - data[index], axis=1))
        return selected

    seed_indices = farthest_point(features, min(args.seed_candidates, len(features)))
    seed_payloads = []
    for index in seed_indices:
        seed_payloads.append(
            payload(
                f"seed{index:04d}", "C_seed", "seed", f"cfg{index}", 0.0,
                rel_r[index], rel_t[index], q=q_all[index].tolist(),
            )
        )
    print(f"seed candidates: {len(seed_payloads)} (farthest-point in relative-pose space)")

    executor = ProcessPoolExecutor(
        max_workers=args.workers,
        mp_context=multiprocessing.get_context("fork"),
        initializer=init_worker,
        initargs=(str(pieces_dir),),
    )
    try:
        print("evaluating A poses and C seed candidates ...")
        first_rows = list(executor.map(evaluate_sample, a_payloads + seed_payloads, chunksize=1))
    finally:
        pass

    a_rows = first_rows[: len(a_payloads)]
    seed_rows = first_rows[len(a_payloads):]
    accepted = [
        row for row in seed_rows
        if row["reference_status"] == "exact" and not row["reference_intersects"]
        and row["reference_distance"] <= 0.030
    ]
    accepted.sort(key=lambda row: row["reference_distance"])
    rejected = [row for row in seed_rows if row not in accepted]
    rejection = dict(
        total=len(seed_rows),
        accepted=len(accepted),
        reference_overlap=sum(1 for row in rejected if row["reference_intersects"]),
        beyond_30mm=sum(
            1 for row in rejected
            if row["reference_status"] == "exact" and not row["reference_intersects"]
            and row["reference_distance"] > 0.030
        ),
        reference_not_exact=sum(1 for row in rejected if row["reference_status"] != "exact"),
    )
    print(f"seeds accepted (reference separated <= 30 mm): {len(accepted)}; rejected {len(rejected)} "
          f"({rejection})")

    # diversity: a new cluster must differ in the Link3 contact region or in relative orientation
    clusters = []
    for row in accepted:
        witness = np.asarray(row["reference_witness_a"]) if row["reference_witness_a"] is not None else None
        rotation = np.asarray(row["rotation"])
        keep = True
        for picked in clusters:
            other_witness = np.asarray(picked["reference_witness_a"]) if picked["reference_witness_a"] is not None else None
            other_rotation = np.asarray(picked["rotation"])
            witness_gap = 0.0 if witness is None or other_witness is None else float(np.linalg.norm(witness - other_witness))
            angle = float(Rotation.from_matrix(rotation @ other_rotation.T).magnitude())
            if witness_gap < 0.012 and angle < math.radians(25.0):
                keep = False
                break
        if keep:
            clusters.append(row)
        if len(clusters) >= args.clusters:
            break
    print(f"independent C clusters selected: {len(clusters)}")

    final_rows: list[dict] = list(a_rows)
    cluster_rows = []
    for number, seed_row in enumerate(clusters, start=1):
        cluster_id = f"C{number:02d}"
        seed_row["type"] = "C"
        seed_row["cluster"] = cluster_id
        seed_row["s"] = 0.0
        seed_row["seed"] = f"C{number:02d}"
        final_rows.append(seed_row)
        cluster_rows.append(seed_row)

    # --- C families: joint-space paths from each accepted seed --------------------------------
    families: dict[str, dict] = {}
    for seed_row in clusters:
        cluster_id = seed_row["cluster"]
        q0 = np.asarray(seed_row["q"])
        chosen = None
        for attempt in range(6):
            direction = rng.uniform(-1.0, 1.0, size=6)
            direction /= max(float(np.abs(direction).max()), 1e-9)
            if attempt:
                direction *= rng.choice([-1.0, 1.0])

            def builder(s: float, q0=q0, direction=direction):
                q = np.clip(q0 + s * direction, LO, HI)
                rotation, translation, *_ = fk(q)
                extra = dict(q=q.tolist(), advance_parameter=float(s),
                             clipped=bool(np.any(np.abs(q - (q0 + s * direction)) > 1e-12)))
                return rotation, translation, extra

            scan = scan_and_boundary(builder, pieces3, pieces5)
            if scan["boundary"] is not None and scan["boundary"][1] > 0:
                chosen = (builder, scan, direction)
                break
            if chosen is None:
                chosen = (builder, scan, direction)
        builder, scan, direction = chosen
        s_values = s_list_from_boundary(scan["boundary"], scan["closest"][0])
        family_id = f"{cluster_id}"
        families[family_id] = dict(kind="C", cluster=cluster_id, seed=cluster_id, builder=builder,
                                   boundary_candidate=scan["boundary"], s_values=set(), payloads=[])
        for s in s_values:
            families[family_id]["s_values"].add(round(s, 7))
            if s == 0.0:
                continue  # the seed row is already evaluated and is reused as this cluster's s=0
            rotation, translation, extra = builder(s)
            families[family_id]["payloads"].append(
                payload(f"{family_id}_s{s:.7f}", "C", cluster_id, cluster_id, s, rotation, translation, **extra)
            )
        print(f"  {cluster_id}: direction {np.round(direction, 2).tolist()}, candidate boundary "
              f"{None if scan['boundary'] is None else tuple(round(v, 4) for v in scan['boundary'])}, "
              f"{len(families[family_id]['payloads'])} initial samples")

    # --- B families: independent rigid transforms ---------------------------------------------
    b_bases = [a_rows[0], a_rows[3]] + clusters[: max(0, args.b_families // 2 - 2)]
    b_payloads = []
    b_families = {}
    for base_index, base in enumerate(b_bases):
        rotation0 = np.asarray(base["rotation"])
        translation0 = np.asarray(base["translation"])
        if base["reference_witness_a"] is None or base["reference_witness_b"] is None:
            continue
        witness_a = np.asarray(base["reference_witness_a"])
        witness_b = np.asarray(base["reference_witness_b"])
        direction0 = witness_a - witness_b
        norm = float(np.linalg.norm(direction0))
        if norm <= 1e-9:
            continue
        direction0 = direction0 / norm
        for variant in range(2):
            if len(b_families) >= args.b_families:
                break
            made = None
            for attempt in range(5):
                angle = math.radians(float(rng.uniform(8.0, 20.0)))
                axis = rng.normal(size=3)
                axis /= np.linalg.norm(axis)
                delta = Rotation.from_rotvec(axis * angle).as_matrix()
                rotation1 = rotation0 @ delta
                translation1 = translation0 + rotation0 @ (centroid5 - delta @ centroid5)
                perturb_axis = rng.normal(size=3)
                perturb_axis /= np.linalg.norm(perturb_axis)
                perturb = Rotation.from_rotvec(
                    perturb_axis * math.radians(float(rng.uniform(0.0, 25.0)))
                ).as_matrix()
                direction = perturb @ direction0
                probe = union_query(pieces3, pieces5, rotation1, translation1)
                if probe["status"] == "intersecting":
                    continue
                # close roughly 0.7 of the candidate distance per unit of the path parameter
                scale = max(float(probe["distance"]) / 0.7, 0.005)
                if not np.isfinite(scale):
                    continue

                def builder(s: float, rotation1=rotation1, translation1=translation1,
                            direction=direction, scale=scale, angle=angle):
                    translation = translation1 + direction * (s * scale)
                    extra = dict(advance_parameter=float(s),
                                 applied_translation=(direction * (s * scale)).tolist(),
                                 applied_rotation_deg=math.degrees(angle))
                    return rotation1, translation, extra

                scan = scan_and_boundary(builder, pieces3, pieces5)
                if scan["boundary"] is not None:
                    made = (builder, scan, direction, scale, angle)
                    break
                if made is None:
                    made = (builder, scan, direction, scale, angle)
            if made is None:
                continue
            builder, scan, direction, scale, angle = made
            family_id = f"B{base_index + 1}_{variant + 1}"
            b_families[family_id] = dict(kind="B", cluster=family_id, seed=f"base{base_index + 1}",
                                         builder=builder, boundary_candidate=scan["boundary"],
                                         s_values=set(), payloads=[])
            for s in s_list_from_boundary(scan["boundary"], scan["closest"][0]):
                rotation, translation, extra = builder(s)
                b_families[family_id]["payloads"].append(
                    payload(f"{family_id}_s{s:.7f}", "B", family_id, f"base{base_index + 1}",
                            s, rotation, translation, **extra)
                )
                b_families[family_id]["s_values"].add(round(s, 7))
            print(f"  {family_id}: scale {scale:.4f} m, rotation {math.degrees(angle):.1f} deg, "
                  f"candidate boundary "
                  f"{None if scan['boundary'] is None else tuple(round(v, 4) for v in scan['boundary'])}, "
                  f"{len(b_families[family_id]['payloads'])} initial samples")

    families.update(b_families)

    # --- initial family evaluation ------------------------------------------------------------
    initial_payloads = [item for family in families.values() for item in family["payloads"]]
    print(f"evaluating {len(initial_payloads)} family samples (reference + hull + pieces) ...")
    initial_rows = list(executor.map(evaluate_sample, initial_payloads, chunksize=1))
    final_rows.extend(initial_rows)

    # --- refinement: fill bins and tighten the reference contact boundary --------------------
    # attach initial results to their families
    for row in initial_rows:
        fid = row["cluster"]
        if fid in families:
            families[fid].setdefault("results", []).append(row)
    for row in cluster_rows:
        families[row["cluster"]].setdefault("results", []).append(row)

    for round_index in range(args.rounds):
        new_payloads = []
        for fid, family in families.items():
            rows = [row for row in family.get("results", []) if row["reference_status"] == "exact"]
            separated = sorted(
                [row for row in rows if not row["reference_intersects"] and row["reference_distance"] > CONTACT_TOL],
                key=lambda row: row["s"],
            )
            overlaps = sorted([row for row in rows if row["reference_intersects"]], key=lambda row: row["s"])
            # missing distance bins
            for (lo, hi) in BINS:
                if any(lo <= row["reference_distance"] < hi for row in separated):
                    continue
                target = 0.5 * (lo + hi)
                bracket = None
                for left, right in zip(separated, separated[1:]):
                    d_left, d_right = left["reference_distance"], right["reference_distance"]
                    if (d_left - target) * (d_right - target) <= 0 and abs(d_right - d_left) > 1e-12:
                        if bracket is None or (right["s"] - left["s"]) < bracket[0]:
                            bracket = (right["s"] - left["s"], left, right)
                if bracket is None:
                    continue
                _, left, right = bracket
                s_target = left["s"] + (target - left["reference_distance"]) * (
                    right["s"] - left["s"]
                ) / (right["reference_distance"] - left["reference_distance"])
                s_target = float(np.clip(s_target, 0.0, 2.0))
                if round(s_target, 7) in family["s_values"]:
                    continue
                rotation, translation, extra = family["builder"](s_target)
                new_payloads.append(
                    payload(f"{fid}_r{round_index}_{s_target:.7f}", family["kind"], family["cluster"],
                            family["seed"], s_target, rotation, translation, **extra)
                )
                family["s_values"].add(round(s_target, 7))
            # first reference overlap: bisect the bracket between separated and intersecting
            if separated and overlaps:
                first_overlap = overlaps[0]
                below = [row for row in separated if row["s"] < first_overlap["s"]]
                if below:
                    left = max(below, key=lambda row: row["s"])
                    s_target = 0.5 * (left["s"] + first_overlap["s"])
                    if round(s_target, 7) not in family["s_values"]:
                        rotation, translation, extra = family["builder"](s_target)
                        new_payloads.append(
                            payload(f"{fid}_r{round_index}_b{s_target:.7f}", family["kind"], family["cluster"],
                                    family["seed"], s_target, rotation, translation, **extra)
                        )
                        family["s_values"].add(round(s_target, 7))
        if not new_payloads:
            print(f"refinement round {round_index + 1}: nothing to add")
            break
        print(f"refinement round {round_index + 1}: {len(new_payloads)} new samples")
        new_rows = list(executor.map(evaluate_sample, new_payloads, chunksize=1))
        final_rows.extend(new_rows)
        for row in new_rows:
            fid = row["cluster"]
            if fid in families:
                families[fid].setdefault("results", []).append(row)

    executor.shutdown(wait=True)

    # Contact boundary per family: the last reference-separated sample and the first reference
    # overlap sample bracket the true boundary. The applied parameter is a path coordinate, not a
    # penetration depth.
    family_boundaries = {}
    non_monotone = []
    for fid, family in families.items():
        rows = [row for row in family.get("results", []) if row["reference_status"] == "exact"]
        separated = sorted(
            [row for row in rows if not row["reference_intersects"] and row["reference_distance"] > CONTACT_TOL],
            key=lambda row: row["s"],
        )
        overlaps = sorted([row for row in rows if row["reference_intersects"]], key=lambda row: row["s"])
        entry = dict(
            candidate_boundary=family.get("boundary_candidate"),
            n_separated=len(separated),
            n_overlap=len(overlaps),
            first_overlap_s=None,
            last_separated_s=None,
            last_separated_distance=None,
            bracket_width_s=None,
        )
        if len(separated) >= 3:
            signs = np.sign(np.diff([row["reference_distance"] for row in separated]))
            for left, right in zip(signs, signs[1:]):
                if left != 0 and right != 0 and left != right:
                    non_monotone.append(fid)
                    break
        if separated and overlaps:
            first = overlaps[0]
            below = [row for row in separated if row["s"] < first["s"]]
            if below:
                last = max(below, key=lambda row: row["s"])
                entry.update(
                    first_overlap_s=first["s"],
                    last_separated_s=last["s"],
                    last_separated_distance=last["reference_distance"],
                    bracket_width_s=first["s"] - last["s"],
                )
        family_boundaries[fid] = entry

    # -----------------------------------------------------------------------------------------
    # Statistics
    # -----------------------------------------------------------------------------------------
    validation = [row for row in final_rows if row.get("type") in ("B", "C")]
    regression = [row for row in final_rows if row.get("type") == "A"]

    def ref_bucket(row: dict) -> str:
        if row["reference_status"] == "certified_culled":
            return "beyond_cap"
        if row["reference_status"] != "exact":
            return "unknown"
        if row["reference_intersects"]:
            return "overlap"
        if row["reference_distance"] <= CONTACT_TOL:
            return "uncertain"
        if row["reference_distance"] <= 0.020:
            return "0-20mm"
        return "far"

    def candidate_state(row: dict) -> str:
        if row["pieces_status"] == "failed":
            return "unknown"
        if row["pieces_intersects"] or row["pieces_distance"] <= CONTACT_TOL:
            return "contact"
        return "separated"

    def error(row: dict) -> float:
        if row["reference_status"] != "exact" or row["reference_intersects"] or row["pieces_status"] == "failed":
            return float("nan")
        return float(row["pieces_distance"] - row["reference_distance"])

    for row in final_rows:
        row["reference_bucket"] = ref_bucket(row)
        row["candidate_state"] = candidate_state(row)
        row["signed_error"] = error(row)
        row["abs_error"] = abs(row["signed_error"]) if np.isfinite(row["signed_error"]) else float("nan")

    def percentile(values: list[float], q: float) -> float:
        values = [v for v in values if np.isfinite(v)]
        return float(np.percentile(values, q)) if values else float("nan")

    separated_20 = [
        row for row in validation if row["reference_bucket"] == "0-20mm" and np.isfinite(row["signed_error"])
    ]

    def summarize(rows: list[dict]) -> dict:
        errors = [row["signed_error"] for row in rows if np.isfinite(row["signed_error"])]
        return dict(
            n=len(rows),
            n_error=len(errors),
            abs_p95=percentile([abs(e) for e in errors], 95),
            abs_max=max((abs(e) for e in errors), default=float("nan")),
            signed_median=percentile(errors, 50),
            signed_min=min(errors, default=float("nan")),
            signed_max=max(errors, default=float("nan")),
            false_contact=sum(1 for row in rows if row["candidate_state"] == "contact"),
            candidate_unknown=sum(1 for row in rows if row["candidate_state"] == "unknown"),
            reference_unknown=sum(1 for row in rows if row["reference_bucket"] == "unknown"),
        )

    bin_summary = {}
    for (lo, hi), label in zip(BINS, BIN_LABELS):
        rows = [
            row for row in validation
            if row["reference_bucket"] == "0-20mm" and lo <= row["reference_distance"] < hi
        ]
        bin_summary[label] = summarize(rows)

    def type_summary(kind: str) -> dict:
        rows = [row for row in validation if row["type"] == kind]
        separated = [
            row for row in rows
            if row["reference_bucket"] == "0-20mm" and np.isfinite(row["signed_error"])
        ]
        entry = summarize(separated)
        entry["bins"] = {
            label: summarize([
                row for row in rows
                if row["reference_bucket"] == "0-20mm" and lo <= row["reference_distance"] < hi
            ])
            for (lo, hi), label in zip(BINS, BIN_LABELS)
        }
        entry["overlap_samples"] = sum(1 for row in rows if row["reference_bucket"] == "overlap")
        entry["missed_overlaps"] = sum(
            1 for row in rows
            if row["reference_bucket"] == "overlap" and row["candidate_state"] == "separated"
        )
        entry["false_contact_all_bins"] = sum(
            1 for row in rows
            if row["candidate_state"] == "contact"
            and row["reference_bucket"] in ("0-20mm", "far")
        )
        entry["reference_seconds_median"] = percentile([row["reference_seconds"] for row in rows], 50)
        entry["reference_seconds_max"] = max((row["reference_seconds"] for row in rows), default=float("nan"))
        return entry

    type_summary_by_kind = {kind: type_summary(kind) for kind in ("C", "B")}

    worst_errors = []
    for row in sorted(
        [row for row in validation if np.isfinite(row["signed_error"])],
        key=lambda row: row["signed_error"],
    )[:5]:
        rotation = np.asarray(row["rotation"])
        translation = np.asarray(row["translation"])
        witness_b_local = None
        if row["reference_witness_b"] is not None:
            witness_b_local = (
                rotation.T @ (np.asarray(row["reference_witness_b"]) - translation)
            ).tolist()
        worst_errors.append(dict(
            id=row["id"], type=row["type"], cluster=row["cluster"], s=row["s"],
            reference=row["reference_distance"], candidate=row["pieces_distance"],
            signed_error=row["signed_error"], pieces_pair=row["pieces_pair"],
            reference_triangle_a=row["reference_triangle_a"],
            reference_triangle_b=row["reference_triangle_b"],
            witness_a_link3=row["reference_witness_a"],
            witness_b_link5_local=witness_b_local,
            applied_translation=row.get("applied_translation"),
            applied_rotation_deg=row.get("applied_rotation_deg"),
        ))

    cluster_summary = {}
    for cluster in sorted({row["cluster"] for row in validation if row["type"] == "C"}):
        rows = [row for row in validation if row["type"] == "C" and row["cluster"] == cluster]
        entry = summarize([row for row in rows if row["reference_bucket"] == "0-20mm"])
        entry["bins"] = sorted({
            label for (lo, hi), label in zip(BINS, BIN_LABELS)
            if any(row["reference_bucket"] == "0-20mm" and lo <= row["reference_distance"] < hi for row in rows)
        })
        entry["overlap_samples"] = sum(1 for row in rows if row["reference_bucket"] == "overlap")
        entry["missed_overlaps"] = sum(
            1 for row in rows if row["reference_bucket"] == "overlap" and row["candidate_state"] == "separated"
        )
        entry["unknown"] = sum(1 for row in rows if row["candidate_state"] == "unknown")
        cluster_summary[cluster] = entry

    overlap_rows = [row for row in validation if row["reference_bucket"] == "overlap"]
    overlap_known = [row for row in overlap_rows if row["candidate_state"] != "unknown"]
    overlap_missed = [row for row in overlap_known if row["candidate_state"] == "separated"]
    overlap_detected = [row for row in overlap_known if row["candidate_state"] == "contact"]

    uncertain_rows = [row for row in validation if row["reference_bucket"] == "uncertain"]
    false_contacts = [
        row for row in validation
        if row["reference_bucket"] in ("0-20mm", "far")
        and row["candidate_state"] == "contact"
    ]
    separated_rows = [row for row in validation if row["reference_bucket"] in ("0-20mm", "far")]

    margins = {}
    for margin in (0.0, 0.005, 0.010):
        known = [
            row for row in validation
            if row["reference_bucket"] in ("0-20mm", "far", "overlap")
            and row["candidate_state"] != "unknown"
            and not (margin == 0.0 and row["reference_bucket"] == "uncertain")
        ]
        if margin == 0.0:
            reference_unsafe = [
                row for row in known
                if row["reference_bucket"] == "overlap" or row["reference_distance"] <= CONTACT_TOL
            ]
            candidate_unsafe = [
                row for row in known if row["candidate_state"] == "contact"
            ]
        else:
            reference_unsafe = [
                row for row in known
                if row["reference_bucket"] == "overlap" or row["reference_distance"] < margin
            ]
            candidate_unsafe = [
                row for row in known
                if row["candidate_state"] == "contact" or row["pieces_distance"] < margin
            ]
        reference_ids = {row["id"] for row in reference_unsafe}
        candidate_ids = {row["id"] for row in candidate_unsafe}
        false_positive = [row for row in known if row["id"] in candidate_ids and row["id"] not in reference_ids]
        false_negative = [row for row in known if row["id"] in reference_ids and row["id"] not in candidate_ids]
        margins[f"{margin * 1000:.0f} mm"] = dict(
            n_known=len(known),
            reference_unsafe=len(reference_ids),
            candidate_unsafe=len(candidate_ids),
            false_positive=len(false_positive),
            false_negative=len(false_negative),
            false_positive_rate=len(false_positive) / len(known) if known else float("nan"),
            false_negative_rate=len(false_negative) / len(reference_ids) if reference_ids else float("nan"),
        )

    optimistic = sorted(
        [row for row in validation if np.isfinite(row["signed_error"]) and row["signed_error"] > 0],
        key=lambda row: row["signed_error"], reverse=True,
    )
    optimistic_tail = [
        dict(id=row["id"], type=row["type"], cluster=row["cluster"], s=row["s"],
             reference=row["reference_distance"], candidate=row["pieces_distance"],
             signed_error=row["signed_error"], pair=row["pieces_pair"])
        for row in optimistic[:10]
    ]

    reference_unknown = [
        row for row in final_rows if row["reference_status"] not in ("exact", "certified_culled")
    ]
    candidate_unknown = [row for row in final_rows if row["candidate_state"] == "unknown"]
    coverage_min = min((row["reference_distance"] for row in separated_rows), default=float("nan"))
    coverage_max = max((row["reference_distance"] for row in separated_rows), default=float("nan"))

    summary = dict(
        generated_at=time.strftime("%Y-%m-%d %H:%M:%S"),
        candidate_dir=str(pieces_dir.relative_to(ROOT)),
        effective_candidate_parameters="CoACD threshold 0.02, relative mode (real_metric=False); see candidate_provenance.json",
        contact_tolerance_m=CONTACT_TOL,
        counts=dict(
            total_rows=len(final_rows),
            validation_B_C=len(validation),
            regression_A=len(regression),
            C_clusters=len(clusters),
            B_families=len(b_families),
            reference_overlap=len(overlap_rows),
            reference_uncertain=len(uncertain_rows),
            reference_unknown=len(reference_unknown),
            candidate_unknown=len(candidate_unknown),
        ),
        coverage=dict(
            reference_separated_min_m=coverage_min,
            reference_separated_max_m=coverage_max,
            bins_present={label: bin_summary[label]["n"] > 0 for label in BIN_LABELS},
        ),
        bin_summary=bin_summary,
        by_type=type_summary_by_kind,
        cluster_summary=cluster_summary,
        overall_0_20=summarize(separated_20),
        worst_errors=worst_errors,
        overlap=dict(
            positives=len(overlap_rows),
            known_candidate=len(overlap_known),
            detected=len(overlap_detected),
            missed=len(overlap_missed),
            unknown=len(overlap_rows) - len(overlap_known),
            miss_rate_known=len(overlap_missed) / len(overlap_known) if overlap_known else float("nan"),
            missed_ids=[row["id"] for row in overlap_missed],
        ),
        false_contact=dict(
            false_contacts=len(false_contacts),
            separated_denominator=len(separated_rows),
            rate=len(false_contacts) / len(separated_rows) if separated_rows else float("nan"),
            uncertain_rows=len(uncertain_rows),
            uncertain_contact=sum(1 for row in uncertain_rows if row["candidate_state"] == "contact"),
            ids=[row["id"] for row in false_contacts[:20]],
        ),
        margins=margins,
        optimistic_tail=optimistic_tail,
        optimistic_tail_n=len(optimistic),
        boundaries=family_boundaries,
        non_monotone_families=sorted(set(non_monotone)),
        regression=dict(
            n=len(regression),
            hull_false_contacts=sum(1 for row in regression if row["hull_intersects"]),
            pieces_false_contacts=sum(1 for row in regression if row["candidate_state"] == "contact"),
            reference_overlaps=sum(1 for row in regression if row["reference_intersects"]),
            pieces_missed=sum(1 for row in regression if row["reference_intersects"] and row["candidate_state"] == "separated"),
        ),
        inventory=inventory,
        seed_rejection=rejection,
    )

    (out_dir / "validation_results.json").write_text(json.dumps(dict(summary=summary, rows=final_rows), indent=1))

    with (out_dir / "validation_samples.csv").open("w", newline="") as handle:
        fields = [
            "id", "type", "cluster", "seed", "s", "advance_parameter", "applied_translation",
            "applied_rotation_deg", "q", "rotation", "translation",
            "reference_distance", "reference_status", "reference_intersects", "reference_bucket",
            "reference_seconds", "reference_triangle_a", "reference_triangle_b",
            "hull_distance", "hull_intersects",
            "pieces_distance", "pieces_status", "pieces_intersects", "pieces_pair",
            "pieces_failed", "pieces_iterations", "pieces_seconds",
            "candidate_state", "signed_error", "abs_error",
        ]
        writer = csv.DictWriter(handle, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        for row in final_rows:
            writer.writerow(row)

    def report() -> str:
        lines = []
        lines.append("=" * 96)
        lines.append("Stage 4.13b candidate validation -- frozen Link3 5 pieces / Link5 13 pieces")
        lines.append("candidate parameters: CoACD threshold 0.02 in RELATIVE mode (real_metric=False)")
        lines.append(f"contact tolerance: {CONTACT_TOL * 1000:.2f} mm (fixed in advance)")
        lines.append("=" * 96)
        lines.append(f"rows: {len(final_rows)} | validation B+C: {len(validation)} | regression A: {len(regression)}")
        lines.append(f"C clusters: {len(clusters)} | B families: {len(b_families)}")
        lines.append(f"reference overlaps: {len(overlap_rows)} | uncertain: {len(uncertain_rows)} | "
                     f"reference unknown: {len(reference_unknown)} | candidate unknown: {len(candidate_unknown)}")
        lines.append("")
        lines.append("Per-bin (reference distance; candidate error = d_candidate - d_reference):")
        for label in BIN_LABELS:
            entry = bin_summary[label]
            lines.append(
                f"  {label:>8}: n={entry['n']:3d} (with error {entry['n_error']:3d})  "
                f"|e| p95={entry['abs_p95'] * 1000:6.2f} mm  "
                f"max={entry['abs_max'] * 1000:6.2f} mm  "
                f"signed median={entry['signed_median'] * 1000:6.2f} mm  "
                f"false contact={entry['false_contact']}  unknown={entry['candidate_unknown']}"
            )
        overall = summary["overall_0_20"]
        lines.append(
            f"  OVERALL: n={overall['n']:3d} (with error {overall['n_error']:3d})  "
            f"|e| p95={overall['abs_p95'] * 1000:6.2f} mm  "
            f"max={overall['abs_max'] * 1000:6.2f} mm"
        )
        lines.append("")
        lines.append("Separated by sample type (B rigid stress, C full-FK robot configurations):")
        for kind in ("C", "B"):
            entry = type_summary_by_kind[kind]
            lines.append(
                f"  {kind}: n={entry['n']:3d} (with error {entry['n_error']:3d})  "
                f"|e| p95={entry['abs_p95'] * 1000:6.2f} mm  max={entry['abs_max'] * 1000:6.2f} mm  "
                f"false contacts={entry['false_contact_all_bins']}  "
                f"overlaps={entry['overlap_samples']} missed={entry['missed_overlaps']}  "
                f"reference time median={entry['reference_seconds_median']:.2f}s"
            )
            bins = ", ".join(
                f"{label}:{entry['bins'][label]['n']}" for label in BIN_LABELS
            )
            lines.append(f"      bins {bins}")
        lines.append("")
        lines.append("Overlap detection (valid positives = reference intersects with a known candidate):")
        lines.append(
            f"  positives={summary['overlap']['positives']}  known={summary['overlap']['known_candidate']}  "
            f"detected={summary['overlap']['detected']}  missed={summary['overlap']['missed']}  "
            f"unknown={summary['overlap']['unknown']}  miss rate={summary['overlap']['miss_rate_known']:.1%}"
            if overlap_known else "  no valid overlap positives"
        )
        lines.append("")
        lines.append("False contact on reference-separated samples:")
        fc = summary["false_contact"]
        lines.append(
            f"  {fc['false_contacts']} / {fc['separated_denominator']} = {fc['rate']:.1%}; "
            f"uncertain-band contacts {fc['uncertain_contact']} / {fc['uncertain_rows']}"
        )
        lines.append("")
        lines.append("Safety margins (false positive / false negative, candidate vs reference):")
        for margin, entry in margins.items():
            lines.append(
                f"  margin {margin:>6}: known={entry['n_known']:3d}  FP={entry['false_positive']:3d} "
                f"({entry['false_positive_rate']:.1%})  FN={entry['false_negative']:3d} "
                f"({entry['false_negative_rate']:.1%})"
            )
        lines.append("")
        lines.append("Per-cluster (C); several samples in one cluster are dense interpolation, not independent evidence:")
        for cluster, entry in cluster_summary.items():
            lines.append(
                f"  {cluster}: n={entry['n']:3d}  |e| p95={entry['abs_p95'] * 1000:6.2f} mm  "
                f"max={entry['abs_max'] * 1000:6.2f} mm  bins={','.join(entry['bins']) or '-'}  "
                f"overlaps={entry['overlap_samples']} missed={entry['missed_overlaps']}"
            )
        lines.append("")
        lines.append("Reference contact boundary per family (last separated / first overlap):")
        for fid, entry in family_boundaries.items():
            if entry["first_overlap_s"] is None:
                lines.append(f"  {fid}: no reference overlap reached "
                             f"(separated {entry['n_separated']}, candidate boundary {entry['candidate_boundary']})")
            else:
                lines.append(
                    f"  {fid}: separated s={entry['last_separated_s']:.5f} "
                    f"d={entry['last_separated_distance'] * 1000:6.3f} mm -> first overlap s="
                    f"{entry['first_overlap_s']:.5f} (bracket {entry['bracket_width_s']:.5f})"
                )
        lines.append(f"non-monotone separated sequences: {summary['non_monotone_families'] or 'none'}")
        lines.append("")
        lines.append("Worst (most conservative) errors, with the responsible geometry:")
        for item in summary["worst_errors"]:
            lines.append(
                f"  {item['id']} [{item['type']}/{item['cluster']}]: ref {item['reference'] * 1000:6.2f} mm, "
                f"candidate {item['candidate'] * 1000:6.2f} mm, error {item['signed_error'] * 1000:6.2f} mm; "
                f"piece pair {item['pieces_pair']}; reference triangles "
                f"({item['reference_triangle_a']}, {item['reference_triangle_b']}); "
                f"witness on Link5 (local) {item['witness_b_link5_local']}"
            )
        lines.append("")
        lines.append(f"optimistic errors > 0: {summary['optimistic_tail_n']}")
        for item in optimistic_tail:
            lines.append(
                f"  {item['id']}: ref {item['reference'] * 1000:6.2f} candidate {item['candidate'] * 1000:6.2f} "
                f"error +{item['signed_error'] * 1000:5.2f} mm ({item['pair']})"
            )
        if overlap_missed:
            lines.append("  reference overlaps the candidate reports as separated: "
                         + ", ".join(row["id"] for row in overlap_missed))
        lines.append("")
        lines.append(f"regression A: hull false contacts {summary['regression']['hull_false_contacts']}/{len(regression)}, "
                     f"pieces false contacts {summary['regression']['pieces_false_contacts']}/{len(regression)}, "
                     f"missed {summary['regression']['pieces_missed']}")
        return "\n".join(lines)

    text = report()
    (out_dir / "validation_summary.txt").write_text(text + "\n")
    print("\n" + text)


if __name__ == "__main__":
    main()
