"""Stage 4.13b: build an independent contact-boundary set and judge the frozen candidate.

The candidate (Link3 5 pieces / Link5 13 pieces, CoACD threshold 0.02 in relative mode) is frozen.
This script does not touch its parameters. It builds three sample classes and measures the
candidate against the original triangle meshes:

A. the six known false-contact regression poses;
B. rigid Link5 transforms, walked toward Link3 from independent seeds (not robot-reachable);
C. configurations inside the joint limits, generated by full MuJoCo forward kinematics.

Every distance bin is decided by the reference mesh distance, never by the applied parameter or by
the candidate's own distance. The contact tolerance is fixed here, before any result is inspected.

The boundary walk uses the candidate only to choose *where* to look. What the sample is called
(separated bin, overlap, unknown) comes from the reference evaluation.

Run:
    conda run -n env_isaaclab5 python scripts/ranger_cr10/validate_candidate_boundary.py
"""

